export type Bytes = Uint8Array;

/** Username as registered on the server. Unique. */
export type UserId = string;

/** Role in a session. The user who starts the session is the initiator. */
export type Role = "initiator" | "responder";

export interface KeyPair {
  publicKey: Bytes;
  privateKey: Bytes;
}

/**
 * Output of a completed handshake (owner: B) and input for ratchet initialization (owner: C).
 * This interface is the boundary that lets B and C work in parallel:
 * C can create a fake HandshakeResult with a random rootKey for testing.
 *
 * - Responder: ownRatchetKeyPair = its handshake ephemeral X25519 key pair (PDF §7).
 * - Initiator: peerRatchetPublicKey = responder's ephemeral public key;
 *              the initiator generates a new ratchet key pair and sends first.
 */
export interface HandshakeResult {
  role: Role;
  sessionId: Bytes; // >= 16 bytes, generated by the initiator
  conversationId: string;
  selfId: UserId;
  peerId: UserId;
  transcriptHash: Bytes;
  rootKey: Bytes; // initial root-key material from HKDF (never the raw ECDH output)
  ownRatchetKeyPair?: KeyPair; // responder only
  peerRatchetPublicKey?: Bytes; // initiator only
}

/** Authenticated (not encrypted) message header. Encoded as AEAD associated data. */
export interface PacketHeader {
  version: string;
  conversationId: string;
  sessionId: Bytes;
  senderId: UserId;
  receiverId: UserId;
  ratchetPublicKey: Bytes; // sender's current DH ratchet public key
  previousChainLength: number; // PN
  messageNumber: number; // N
}

export interface EncryptedPacket {
  header: PacketHeader;
  ciphertext: Bytes; // AES-256-GCM output including the tag
}
